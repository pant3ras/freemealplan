export function ingredientName(ing: Ingredient, lang: Lang): string {
  return lang === 'ro' ? (ing.nameRo ?? INGREDIENT_NAMES_RO[ing.id] ?? ing.name) : ing.name;
}

export function recipeName(r: Recipe, lang: Lang): string {
  return pick(r.name, lang);
}

/** "Mon" / "Mon 2 Nov" in English, "Lun" / "Lun 2 nov." in Romanian. */
export function dayLabel(d: Date, lang: Lang, long = false): string {
  const c = COMMON[lang];
  const name = c.days[(d.getDay() + 6) % 7];
  return long ? `${name} ${d.getDate()} ${c.months[d.getMonth()]}` : name;
}
